/* ===========================================================================
   deepen.js — 願いの解像度を上げる問い（AIなしの既定エンジン）
   ---------------------------------------------------------------------------
   AI を使わない人にも、同じ場所が動くようにするための仕組み。
   通信もしないし、鍵も要らない。願いのどこが空白かを見て、そこを突く問いを選ぶ。

   AI ほど的確ではありません。でも「訊かれること」自体に価値があるので、
   何も出ないより、こちらのほうがずっとよいと考えました。
   =========================================================================== */
(function (W) {
  'use strict';

  /* 意味の幅が広すぎて、そのままでは像を結ばない語 */
  var VAGUE = /(もっと|ちゃんと|うまく|しっかり|きちんと|よい|良い|いい感じ|幸せ|成功|充実|豊か|自由|安定|健康|前向き|ポジティブ|自分らしく|理想の|素敵な|楽しい)/;
  /* 人が出てくるか */
  var WHO   = /(人|誰|友|家族|母|父|子|妻|夫|恋人|仲間|同僚|上司|客|読者|生徒|patient|チーム|世界|社会)/;
  /* 時期が入っているか */
  var WHEN  = /(まで|今年|来年|月|日|週|朝|夜|毎日|いつ|年内|季節|春|夏|秋|冬)/;
  /* 数や量が入っているか */
  var COUNT = /[0-9０-９]|(ひとつ|一つ|三人|何人|回|冊|本|件|人分)/;

  /* 問いの候補。gap が true のものから先に選ぶ。 */
  function pool(wish) {
    var t = wish.title || '', e = wish.essence || '', s = wish.scene || '';
    var all = t + ' ' + e + ' ' + s;

    return [
      { gap: !e || e.length < 12, axis: '芯',
        q: 'この願いが叶ったとき、私の何が満たされているだろう？',
        why: '「なぜ」が書かれていません。ここが弱いと、願いは途中で他人のものにすり替わります。' },

      { gap: !s || s.length < 12, axis: '情景',
        q: 'それが叶っている場面を思い浮かべたとき、目の前に何が見えているだろう？',
        why: '情景が書かれていません。見えている絵があるほど、日々の兆しに気づけます。' },

      { gap: VAGUE.test(t), axis: '具体',
        q: 'この願いのなかで、いちばんぼんやりしている言葉はどれだろう。それを別の言葉で言うと？',
        why: '広い意味の言葉が入っています。広い言葉は、叶ったかどうかを自分で判定できません。' },

      { gap: !WHO.test(all), axis: '相手',
        q: 'この願いが叶うとき、そこには誰がいるだろう？',
        why: '人が出てきていません。相手が決まると、願いは急に具体になります。' },

      { gap: !WHEN.test(all), axis: '時',
        q: 'この願いは、いつごろの話をしているのだろう。次の満月まで、で言えることはある？',
        why: '時期が入っていません。「いつか」は永遠に来ない日です。' },

      { gap: !COUNT.test(all), axis: '量',
        q: 'これが叶ったと言えるのは、何がどれだけ起きたときだろう？',
        why: '数や量がありません。叶った瞬間を、自分で見分けられるようにしておきます。' },

      { gap: t.length > 34, axis: '核',
        q: 'この願いをふたつに割るとしたら、どちらが芯で、どちらがおまけだろう？',
        why: '願いが長めです。ふたつ以上のことが混ざっていると、どちらも進みません。' },

      /* 以下は空白と関係なく、いつでも効く問い。
         「空白を埋める問い」とは種類が違うので、always で区別する。 */
      { always: true, axis: '根',
        q: 'これが叶わなかったとしても、私が本当に欲しかったものは何だろう？',
        why: '願いの下にあるものが見えると、叶え方はひとつではなくなります。' },

      { always: true, axis: '最小',
        q: 'この願いを、いちばん小さい形にすると何になるだろう？',
        why: '小さい形が見えると、今日ふれることができます。' },

      { always: true, axis: '代償',
        q: 'これが叶うとき、私は何を手放すことになるだろう？',
        why: '失うものが見えていない願いは、途中で足が止まりがちです。' },

      { always: true, axis: '出所',
        q: 'この願いを、私は誰の言葉で語っているだろう？',
        why: '借りものの願いは、強く思えません。' },

      { always: true, axis: '既に',
        q: 'この願いのうち、すでに叶っている部分はどこだろう？',
        why: '全部が未達に見えているときほど、もう手の中にある部分があります。' }
    ];
  }

  /* 4つ選ぶ。順番は「空白を突く問い → 常設の問い」。
     大事なのは、空白でない項目の問いを落とすこと。すでに情景を書いている人に
     「情景はどうなっていますか」と訊いたら、それは読んでいないのと同じで、
     いちばん興ざめする。埋まっている願いには、より深いほうの問いを出す。 */
  function questionsFor(wish, existing) {
    var have = (existing || []).map(function (q) { return q.text; }).join(' ');
    var cand = pool(wish).filter(function (c) {
      if (!have) return true;
      // 同じ語がふたつ以上重なっていたら、すでに訊かれているとみなす
      var key = c.q.replace(/[^一-龥ァ-ヴ]/g, '').slice(0, 6);
      return key.length < 3 || have.indexOf(key) < 0;
    });

    var gaps = cand.filter(function (c) { return c.gap; });
    var rest = cand.filter(function (c) { return c.always; });
    // c.gap === false のもの（＝すでに書かれている項目の問い）は、ここで捨てる

    // 常設の問いは毎回同じ順だと飽きるので、願いごとに順番を変える
    var seed = 0;
    (wish.id || '').split('').forEach(function (ch) { seed = (seed * 31 + ch.charCodeAt(0)) % 9973; });
    rest.sort(function (a, b) {
      return ((seed + a.q.length) % 7) - ((seed + b.q.length) % 7);
    });

    return gaps.concat(rest).slice(0, 4);
  }

  /* 答えから言い直しの候補を作る（AIなし版）。
     こちらでは新しい文を組み立てず、本人が書いた答えをそのまま並べて、
     「この材料で書き直してください」と返す。下手に自動生成すると、
     本人の言葉でない願いができあがってしまうため。 */
  function materialsFor(qa) {
    return qa.filter(function (x) { return x.a && x.a.trim(); })
             .map(function (x) { return { q: x.q, a: x.a.trim() }; });
  }

  W.deepen = { questionsFor: questionsFor, materialsFor: materialsFor, pool: pool };
})(window.W = window.W || {});
