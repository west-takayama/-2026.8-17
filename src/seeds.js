/* ===========================================================================
   seeds.js — 問いの種
   ---------------------------------------------------------------------------
   月相ごとに用意した問いの雛形。「今日の問い」はここから日替わりで選ばれる。
   自分で思いつかない日でも、問いが途切れないようにするための備え。
   気に入ったものは〈問い〉に写して、自分の言葉に書き換えて育てる。
   =========================================================================== */
(function (W) {
  'use strict';

  var SEEDS = {
    /* 新月：種をまく */
    new: [
      'もし何ひとつ制限がないとしたら、私は本当は何を望んでいるだろう？',
      'この願いを、いちばん短い一文で言うとどうなるだろう？',
      'この願いは、本当に私自身のものだろうか。誰かの声が混じっていないだろうか？',
      'これから一か月、私が育てたいものは何だろう？'
    ],
    /* 三日月：小さく動く */
    crescent: [
      '今日、5分でできるいちばん小さな一歩は何だろう？',
      'まだ小さくて見えにくい変化は、どこに芽を出しているだろう？',
      '今日ひとこと伝えるとしたら、誰に、何を伝えるだろう？',
      'この願いのために、私が今日やめられることは何だろう？'
    ],
    /* 上弦：壁と向き合う */
    first: [
      '今、私を止めているものの正体は何だろう？',
      'その壁は本当に壁だろうか。それとも私の思い込みだろうか？',
      '今日、決めてしまえることは何だろう？',
      '私が怖れているのは失敗だろうか、それとも叶ってしまうことだろうか？'
    ],
    /* 十三夜：問いを研ぐ */
    gibbous1: [
      '私はいま、答えを急いでいないだろうか？',
      'この願いをもう一段深く言い換えると、どうなるだろう？',
      '私が本当に欲しかったのは、これの「何」だろう？',
      '10年後の私なら、この問いをどう書き直すだろう？'
    ],
    /* 満月：感謝と手放し */
    full: [
      'すでに叶っている部分は、どこにあるだろう？',
      '今日、感謝できることを三つ挙げるとしたら何だろう？',
      '私はこの願いを、どれくらい強く握りしめているだろう？',
      '想像とちがう形で叶ったとしても、私はそれを受け取れるだろうか？'
    ],
    /* 十六夜：分かち合う */
    gibbous2: [
      'この願いが叶ったら、まわりには何が起きるだろう？',
      '今日の気づきを一言にするなら、どんな言葉になるだろう？',
      'いま誰かに手渡せる形になっているものは何だろう？',
      '私が受け取ったものを、誰に返せるだろう？'
    ],
    /* 下弦：手放す */
    last: [
      'もう手放してよいものは何だろう？',
      '叶わなかったとしても、私が本当に欲しかったものは何だろう？',
      '「こうでなければ」を一つ外すとしたら、どれだろう？',
      'この願いをいったん置いてみたら、何が起きるだろう？'
    ],
    /* 有明：ゆだねる */
    balsamic: [
      '今日は、何もしないでいられるだろうか？',
      '静かにしていると、何が聞こえてくるだろう？',
      '私がゆだねられる相手や流れは、どこにあるだろう？',
      '次の新月に、私はどんな種をまきたいだろう？'
    ]
  };

  /* 日付から決める。同じ日に開き直しても同じ問いが出るように。 */
  function daily(date) {
    var d = date || new Date();
    var key = W.moon.phase(d).key;
    var list = SEEDS[key] || SEEDS.new;
    var dayNo = Math.floor(new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime() / 86400000);
    return list[dayNo % list.length];
  }

  function forPhase(key) { return SEEDS[key] || []; }

  W.seeds = { SEEDS: SEEDS, daily: daily, forPhase: forPhase };
})(window.W = window.W || {});
